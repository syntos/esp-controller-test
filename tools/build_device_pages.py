#!/usr/bin/env python3
"""Build components/fallback_engine/pages.h: the two web pages served by the controller.

Sources are in tools/device/ (style.css, lang.js, header.html, main.html, setup.html).
The logo images are scaled down so the pages stay small. Run after editing a source file:
    python tools/build_device_pages.py
"""
import base64
import io
import os
import re

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "device")


def read(name):
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        return f.read()


def logo_b64(path, height):
    im = Image.open(os.path.join(ROOT, "site", "assets", path)).convert("RGBA")
    h = height * 2  # 2x for sharp rendering on high-density screens
    im = im.resize((round(im.width * h / im.height), h), Image.LANCZOS).quantize(64)
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


def squeeze(text):
    """Strip indentation and blank lines (the sources are written with ';' and braces, so this is safe)."""
    lines = [ln.strip() for ln in text.splitlines()]
    return "\n".join(ln for ln in lines if ln)


def assemble(name):
    html = read(name)
    html = html.replace("__HEADER__", read("header.html"))
    html = html.replace("__CSS__", squeeze(read("style.css")))
    html = html.replace("__LANGJS__", squeeze(read("lang.js")))
    html = html.replace("__ICON__", logo_b64("logo-icon.png", 38))
    html = html.replace("__WORD__", logo_b64("logo-text.png", 21))
    assert ')HTML"' not in html
    return squeeze(html)


out = ["// GENERATED by tools/build_device_pages.py from tools/device/. Do not edit by hand.",
       "#pragma once", "",
       "namespace esphome {", "namespace fallback_engine {", ""]
for const, src in (("SETUP_PAGE", "setup.html"), ("PAGE", "main.html")):
    html = assemble(src)
    print("%s: %d bytes" % (const, len(html)))
    out.append('static const char *const %s = R"HTML(%s)HTML";' % (const, html))
    out.append("")
out += ["}  // namespace fallback_engine", "}  // namespace esphome", ""]
with open(os.path.join(ROOT, "components", "fallback_engine", "pages.h"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))
